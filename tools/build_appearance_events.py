"""Build the supported actor event observer embedded in all loader packages."""
from pathlib import Path
import hashlib, subprocess
ROOT=Path(__file__).resolve().parents[1]
def main():
    vcvars=Path('C:/Program Files/Microsoft Visual Studio/2022/Community/VC/Auxiliary/Build/vcvars64.bat')
    out=ROOT/'dist/native-appearance-events';out.mkdir(parents=True,exist_ok=True)
    command=f'"{vcvars}" >nul && cl /nologo /LD /MT /O2 /W4 "{ROOT / "native/appearance_events.c"}" /link /OUT:EpicLutAppearanceEvents.dll'
    subprocess.run('cmd.exe /d /s /c "'+command+'"',cwd=out,check=True)
    data=(out/'EpicLutAppearanceEvents.dll').read_bytes();digest=hashlib.sha256(data).hexdigest()
    (ROOT/'src/gear/appearance_event_binary.lua').write_text(
        "-- Generated by tools/build_appearance_events.py; identical for BSL, LLL and MDL.\n"
        f"return {{name='Epic LUT Appearance Events V1',sha256='{digest}',hex='{data.hex()}'}}\n",encoding='utf-8')
    print(digest)
if __name__=='__main__':main()
