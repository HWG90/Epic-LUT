"""Build the engine-supported event helper and embed identical bytes for all loaders."""
from pathlib import Path
import hashlib
import os
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def main():
    vcvars = Path(os.environ.get('ProgramFiles', r'C:\Program Files')) / 'Microsoft Visual Studio/2022/Community/VC/Auxiliary/Build/vcvars64.bat'
    output = ROOT / 'dist/native-weapon-events'
    output.mkdir(parents=True, exist_ok=True)
    command = f'"{vcvars}" >nul && cl /nologo /LD /MT /O2 /W4 "{ROOT / "native/weapon_events.c"}" /link /OUT:EpicLutWeaponEvents.dll'
    subprocess.run('cmd.exe /d /s /c "' + command + '"', cwd=output, check=True)
    binary = (output / 'EpicLutWeaponEvents.dll').read_bytes()
    digest = hashlib.sha256(binary).hexdigest()
    (ROOT / 'src/weapons/weapon_event_binary.lua').write_text(
        "-- Generated by tools/build_weapon_events.py; shared by BSL, LLL and MDL.\n"
        f"return {{name='Epic LUT Event Watch V4', sha256='{digest}', hex='{binary.hex()}'}}\n",
        encoding='utf-8')
    print(digest)

if __name__ == '__main__':
    main()

