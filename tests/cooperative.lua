local C=require('src.core.cooperative')
local ok,a,b,c=C.call(function()return 1,nil,3 end)
assert(ok and a==1 and b==nil and c==3)
local ok,why=C.call(function()error('expected-error',0)end)
assert(not ok and tostring(why):find('expected-error',1,true))
local child=coroutine.create(function()
    local ok,value,last=C.call(function(x)
        local resumed=coroutine.yield(x,nil,'pause')
        assert(resumed=='continue')
        coroutine.yield('second')
        return nil,'complete'
    end,'first')
    assert(ok and value==nil and last=='complete')
end)
local ok,a,b,c=coroutine.resume(child)
assert(ok and a=='first' and b==nil and c=='pause')
local ok,a=coroutine.resume(child,'continue');assert(ok and a=='second')
assert(coroutine.resume(child) and coroutine.status(child)=='dead')
local ok,why=C.call(function()coroutine.yield()end)
assert(not ok and tostring(why):find('scheduled coroutine',1,true))
print('PASS stock cooperative protected-call tuples, yield/resume and errors')
