local c = dofile('src/preview/player_preview_controls.lua').new()
local hit, event = c.pointer(40, 660, true, 1920, 1080)
assert(hit and event == nil)
c.pointer(400, 700, true, 1920, 1080)
assert(c.x == 392 and c.y == 190)
c.pointer(400, 700, false, 1920, 1080)
hit, event = c.pointer(c.x + c.w - 10, c.y + c.h + 10, true, 1920, 1080)
assert(hit and event == 'close')
c.pointer(0, 0, false, 1920, 1080)
hit, event = c.pointer(c.x + c.w * 0.75, c.y - 10, true, 1920, 1080)
assert(hit and event == 'zoom' and c.fov == 25)
for i = 1, 20 do
    c.pointer(0, 0, false, 1920, 1080)
    c.pointer(c.x + c.w * 0.75, c.y - 10, true, 1920, 1080)
end
assert(c.fov == 12)
assert(not c.pointer(0, 0, false, 1920, 1080))
local x, y = c.x, c.y
c.pointer(x + 10, y + c.h + 10, true, 1920, 1080)
c.cancel()
c.pointer(x + 80, y + c.h + 80, true, 1920, 1080)
assert(c.x == x and c.y == y and not c.drag, 'Focus loss left a drag active')
c.pointer(nil, nil, false, 1920, 1080)
assert(not c.held and not c.drag)
local top = c.y + c.h
local oldw = c.w
c.pointer(c.x + c.w - 10, c.y - 10, true, 1920, 1080)
hit, event = c.pointer(c.x + oldw + 50, c.y - 110, true, 1920, 1080)
assert(hit and event == 'resize' and c.w > oldw and math.abs(c.y + c.h - top) < 0.001)
c.pointer(0, 0, false, 1920, 1080)
c.pointer(c.x + c.w - 10, c.y - 10, true, 1920, 1080)
c.pointer(-500, 1000, true, 1920, 1080)
assert(c.w == 240 and c.h == 400, 'Resize failed its minimum bounds')
c.pointer(0, 0, false, 1920, 1080)
local start = c.x + 30
c.pointer(start, c.y + 50, false, 1920, 1080, true)
hit, event = c.pointer(start + c.w / 4, c.y + 50, false, 1920, 1080, true)
assert(hit and event == 'rotate' and c.yaw == 90)
c.pointer(start + c.w, c.y + 50, false, 1920, 1080, true)
assert(c.yaw == 0, 'Orbit did not wrap at 360 degrees')
c.cancel()
assert(not c.orbit and not c.resize)
c.pointer(0, 0, false, 1920, 1080, false)
c.pointer(c.x + 20, c.y + 20, true, 1920, 1080, false)
hit, event = c.pointer(c.x + 1000, c.y + 1000, true, 1920, 1080, false)
assert(hit and event == 'pan' and c.pan_x == 0.25 and c.pan_y == 1)
c.pointer(c.x - 1000, c.y - 1000, true, 1920, 1080, false)
assert(c.pan_x == -0.25 and c.pan_y == -1)
c.cancel()
assert(not c.pan)
print('PASS preview drag, close, zoom limits and pointer isolation')
